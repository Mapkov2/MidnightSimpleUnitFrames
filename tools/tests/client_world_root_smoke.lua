local root = assert(arg[1]):gsub('\\', '/'):gsub('/$', '')
local W = assert(loadfile(root .. '/tools/tests/client_world.lua'))()
local world = W.New('.', 'Mainline')
assert(world.root:match('^%a:/') or world.root:sub(1, 1) == '/', 'test root is not absolute: ' .. world.root)
assert(world.root == W.New(root, 'Mainline').root, 'relative and absolute roots differ')
local graph = W.Graph('.', W.CoreTOC('Mainline'), 'enUS')
assert(#graph > 0 and graph[1]:sub(1, #world.root) == world.root, 'Graph root remained relative')
assert(W.New('./tools/..', 'Mainline').root == world.root, 'dot segments differ')
print('client_world: dot and dot-segment roots resolve to the absolute checkout')
